import { unlink, writeFile } from "node:fs/promises";
import type { S3Client } from "@aws-sdk/client-s3";

import { pool } from "../config/database";
import { env } from "../config/env";
import {
  filenameFromUrl,
  resolveUploadPath,
  UPLOAD_MOUNT_PATH,
} from "./uploadService";

/**
 * Where uploaded product images live. Three drivers:
 *
 * - "local": the API's disk (UPLOAD_DIR), served from /uploads.
 *   Simple, but the files are lost on redeploy and not shared
 *   between instances.
 * - "s3": S3 or any S3-compatible object storage (R2, MinIO, ...).
 *   Set STORAGE_DRIVER=s3 plus the S3_* variables to enable.
 * - "supabase": Supabase Storage on an existing project. Set
 *   STORAGE_DRIVER=supabase plus the SUPABASE_* variables to
 *   enable. Uploads go through the REST API with the service role
 *   key; objects are served from the bucket's public URL.
 */
export interface StorageDriver {
  readonly kind: "local" | "s3" | "supabase";

  /** Persist verified image bytes. Resolves false when the write fails. */
  storeImage(
    filename: string,
    bytes: Buffer,
    mime: string
  ): Promise<boolean>;

  /** Remove a stored file. Already-gone files resolve true. */
  deleteImage(filename: string): Promise<boolean>;

  /** Public URL for a stored file. */
  publicUrl(filename: string): string;

  /**
   * Extract the filename from one of this driver's public URLs, or
   * null when the URL is not managed by this driver (external URLs
   * are never ours to delete).
   */
  filenameFromPublicUrl(url: string): string | null;
}

/** Storage filenames are generated by the server and always safe. */
const FILENAME_PATTERN = /^[A-Za-z0-9._-]+$/;

class LocalStorageDriver implements StorageDriver {
  readonly kind = "local" as const;

  async storeImage(
    filename: string,
    bytes: Buffer
  ): Promise<boolean> {
    const target = resolveUploadPath(filename);

    if (!target) {
      return false;
    }

    try {
      await writeFile(target, bytes);

      return true;
    } catch (error) {
      console.error("Local image store error:", error);

      return false;
    }
  }

  async deleteImage(filename: string): Promise<boolean> {
    const target = resolveUploadPath(filename);

    if (!target) {
      return false;
    }

    try {
      await unlink(target);

      return true;
    } catch (error) {
      // Already gone is still the desired end state.
      if ((error as NodeJS.ErrnoException).code === "ENOENT") {
        return true;
      }

      console.error("Local image delete error:", error);

      return false;
    }
  }

  publicUrl(filename: string): string {
    // Relative by default so URLs survive origin changes; see
    // buildPublicUrl's history in git for the absolute-URL pitfalls.
    const base = env.publicAssetUrl
      ? `${env.publicAssetUrl.replace(/\/+$/, "")}`
      : "";

    return `${base}${UPLOAD_MOUNT_PATH}/${filename}`;
  }

  filenameFromPublicUrl(url: string): string | null {
    return filenameFromUrl(url);
  }
}

class S3StorageDriver implements StorageDriver {
  readonly kind = "s3" as const;

  private client: S3Client | null = null;

  /** Public base URL for stored objects. */
  private publicBase(): string {
    const base = env.s3PublicUrl
      ? env.s3PublicUrl
      : env.s3Endpoint
        ? `${env.s3Endpoint}/${env.s3Bucket}`
        : `https://${env.s3Bucket}.s3.${env.s3Region}.amazonaws.com`;

    return base.replace(/\/+$/, "");
  }

  private async getClient(): Promise<S3Client> {
    if (!this.client) {
      // Loaded lazily so deployments using the local driver never
      // pay for (or even import) the SDK.
      const { S3Client } = await import("@aws-sdk/client-s3");

      this.client = new S3Client({
        region: env.s3Region,
        ...(env.s3Endpoint
          ? { endpoint: env.s3Endpoint }
          : {}),
        credentials: {
          accessKeyId: env.s3AccessKeyId,
          secretAccessKey: env.s3SecretAccessKey,
        },
      });
    }

    return this.client;
  }

  async storeImage(
    filename: string,
    bytes: Buffer,
    mime: string
  ): Promise<boolean> {
    if (!FILENAME_PATTERN.test(filename)) {
      return false;
    }

    try {
      const { PutObjectCommand } = await import(
        "@aws-sdk/client-s3"
      );

      const client = await this.getClient();

      await client.send(
        new PutObjectCommand({
          Bucket: env.s3Bucket,
          Key: filename,
          Body: bytes,
          ContentType: mime,
        })
      );

      return true;
    } catch (error) {
      console.error("S3 image store error:", error);

      return false;
    }
  }

  async deleteImage(filename: string): Promise<boolean> {
    if (!FILENAME_PATTERN.test(filename)) {
      return false;
    }

    try {
      const { DeleteObjectCommand } = await import(
        "@aws-sdk/client-s3"
      );

      const client = await this.getClient();

      // Deleting a key that no longer exists still succeeds, which
      // is exactly the idempotency we want.
      await client.send(
        new DeleteObjectCommand({
          Bucket: env.s3Bucket,
          Key: filename,
        })
      );

      return true;
    } catch (error) {
      console.error("S3 image delete error:", error);

      return false;
    }
  }

  publicUrl(filename: string): string {
    return `${this.publicBase()}/${filename}`;
  }

  filenameFromPublicUrl(url: string): string | null {
    const base = this.publicBase();

    if (!url.startsWith(`${base}/`)) {
      return null;
    }

    const filename = decodeURIComponent(
      url.slice(base.length + 1)
    );

    return FILENAME_PATTERN.test(filename) ? filename : null;
  }
}

class SupabaseStorageDriver implements StorageDriver {
  readonly kind = "supabase" as const;

  /** Authenticated object URL used for writes and deletes. */
  private objectUrl(filename: string): string {
    return `${this.projectBase()}/storage/v1/object/${env.supabaseBucket}/${filename}`;
  }

  /** Public base URL for stored objects (public buckets). */
  private publicBase(): string {
    return `${this.projectBase()}/storage/v1/object/public/${env.supabaseBucket}`;
  }

  private projectBase(): string {
    return env.supabaseUrl.replace(/\/+$/, "");
  }

  async storeImage(
    filename: string,
    bytes: Buffer,
    mime: string
  ): Promise<boolean> {
    if (!FILENAME_PATTERN.test(filename)) {
      return false;
    }

    try {
      const response = await fetch(this.objectUrl(filename), {
        method: "POST",
        headers: {
          Authorization: `Bearer ${env.supabaseServiceKey}`,
          "Content-Type": mime,
          // Same generated name can be retried after a failed store.
          "x-upsert": "true",
        },
        body: new Uint8Array(bytes),
      });

      if (!response.ok) {
        console.error(
          `Supabase image store error: ${response.status} ${await response.text()}`
        );

        return false;
      }

      return true;
    } catch (error) {
      console.error("Supabase image store error:", error);

      return false;
    }
  }

  async deleteImage(filename: string): Promise<boolean> {
    if (!FILENAME_PATTERN.test(filename)) {
      return false;
    }

    try {
      const response = await fetch(this.objectUrl(filename), {
        method: "DELETE",
        headers: {
          Authorization: `Bearer ${env.supabaseServiceKey}`,
        },
      });

      // Already gone is still the desired end state.
      if (!response.ok && response.status !== 404) {
        console.error(
          `Supabase image delete error: ${response.status} ${await response.text()}`
        );

        return false;
      }

      return true;
    } catch (error) {
      console.error("Supabase image delete error:", error);

      return false;
    }
  }

  publicUrl(filename: string): string {
    return `${this.publicBase()}/${filename}`;
  }

  filenameFromPublicUrl(url: string): string | null {
    const base = this.publicBase();

    if (!url.startsWith(`${base}/`)) {
      return null;
    }

    const filename = decodeURIComponent(
      url.slice(base.length + 1)
    );

    return FILENAME_PATTERN.test(filename) ? filename : null;
  }
}

let activeDriver: StorageDriver | null = null;

/**
 * Names of the S3_* variables still required to enable the s3
 * driver. Empty when the configuration is complete.
 */
export function missingS3Config(): string[] {
  const required: [key: string, value: string][] = [
    ["S3_BUCKET", env.s3Bucket],
    ["S3_REGION", env.s3Region],
    ["S3_ACCESS_KEY_ID", env.s3AccessKeyId],
    ["S3_SECRET_ACCESS_KEY", env.s3SecretAccessKey],
  ];

  return required
    .filter(([, value]) => !value)
    .map(([key]) => key);
}

/**
 * Names of the SUPABASE_* variables still required to enable the
 * supabase driver. Empty when the configuration is complete.
 */
export function missingSupabaseConfig(): string[] {
  const required: [key: string, value: string][] = [
    ["SUPABASE_URL", env.supabaseUrl],
    ["SUPABASE_SERVICE_KEY", env.supabaseServiceKey],
    ["SUPABASE_BUCKET", env.supabaseBucket],
  ];

  return required
    .filter(([, value]) => !value)
    .map(([key]) => key);
}

/**
 * The configured storage driver. Throws at startup (fail fast) when
 * STORAGE_DRIVER=s3 or STORAGE_DRIVER=supabase is set without the
 * driver's required credentials.
 */
export function getStorageDriver(): StorageDriver {
  if (activeDriver) {
    return activeDriver;
  }

  if (env.storageDriver === "s3") {
    const missing = missingS3Config();

    if (missing.length > 0) {
      throw new Error(
        `STORAGE_DRIVER=s3 requires ${missing.join(", ")} to be set.`
      );
    }

    activeDriver = new S3StorageDriver();
  } else if (env.storageDriver === "supabase") {
    const missing = missingSupabaseConfig();

    if (missing.length > 0) {
      throw new Error(
        `STORAGE_DRIVER=supabase requires ${missing.join(", ")} to be set.`
      );
    }

    activeDriver = new SupabaseStorageDriver();
  } else {
    activeDriver = new LocalStorageDriver();
  }

  return activeDriver;
}

/**
 * Best-effort deletion of stored files whose URLs are no longer
 * referenced by any product. Runs after a product update/delete
 * commits; failures are logged but never fail the request.
 */
export async function removeUnreferencedImages(
  urls: string[]
): Promise<void> {
  if (urls.length === 0) {
    return;
  }

  const driver = getStorageDriver();

  for (const url of urls) {
    const filename = driver.filenameFromPublicUrl(url);

    // External URLs are not ours to delete.
    if (!filename) {
      continue;
    }

    try {
      const remaining = await pool.query(
        `
        SELECT COUNT(*)::int AS count
        FROM product_images
        WHERE url = $1
        `,
        [url]
      );

      if (remaining.rows[0]?.count === 0) {
        await driver.deleteImage(filename);
      }
    } catch (error) {
      console.error("Image cleanup error:", error);
    }
  }
}
